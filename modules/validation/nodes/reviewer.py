import json
from datetime import datetime
from pathlib import Path
from modules.config import VALIDATION_REPORTS_DIR
from ..state import ValidationState


def reviewer(state: ValidationState) -> ValidationState:
    print("\n[Validation] Evaluating all findings and compiling final report...")
    results = state.get("validation_results", [])
    if not results:
        print("[Validation] WARNING: No validation results to evaluate.")
        return {
            "all_done": True,
            "summary": "Validation finished without any evaluated files.",
        }
    total_files = len(results)
    successful_parses = sum((1 for r in results if r["status"] == "success"))
    failed_parses = sum((1 for r in results if r["status"] == "failed"))
    total_triples = sum((r["total_triples"] for r in results))
    total_subjects = sum((r["validated_subjects"] for r in results))
    total_critical = sum((r["critical_errors_count"] for r in results))
    total_errors = sum((r["errors_count"] for r in results))
    total_warnings = sum((r["warnings_count"] for r in results))
    quality_score = 100.0
    if total_triples > 0:
        quality_score = max(
            0.0, (1.0 - (total_errors + total_critical * 10) / total_triples) * 100
        )
    quality_score_str = f"{quality_score:.2f}%"
    quality_tier = "EXCELLENT (A)"
    if quality_score < 95.0:
        quality_tier = "GOOD (B)"
    if quality_score < 85.0:
        quality_tier = "FAIR (C)"
    if quality_score < 70.0:
        quality_tier = "POOR (D / FAILED)"
    reports_dir = VALIDATION_REPORTS_DIR
    reports_dir.mkdir(parents=True, exist_ok=True)
    timestamp_filename = datetime.now().strftime("%Y%m%d_%H%M%S")
    timestamp_readable = datetime.now().strftime("%d %B %Y, %H:%M:%S")
    md_report_file = reports_dir / f"validation_report_{timestamp_filename}.md"
    json_report_file = reports_dir / f"validation_report_{timestamp_filename}.json"
    md_content = f"# SEMANTIC QUALITY ASSURANCE REPORT\n## EVALUATION OF CONFORMANCE, MANDATORY TRIPLES, AND ANOMALIES ON SEPSES CSKG\n\n## Overview\n* System: SEPSES Cyber-KG Validation Pipeline\n* Timestamp: {timestamp_readable}\n* Evaluated Files: {total_files} Turtle (.ttl) files\n* Total Triples: {total_triples:,}\n* Syntax Status: {successful_parses} Passed, {failed_parses} Failed\n\n## 1. Executive Summary\nThis report evaluates the semantic data quality of the cybersecurity knowledge graph generated by the SEPSES pipeline. The evaluation covers ontology conformance, mandatory triple presence, and anomaly detection in literal values and relation targets.\n\nResult Summary:\n* Semantic Compliance Index: {quality_score_str}\n* Quality Tier: {quality_tier}\n\n## 2. Global Evaluation Metrics\n\n| File Name | Total Triples | Unique Subjects | Errors | Warnings | Parse Status |\n| :--- | :---: | :---: | :---: | :---: | :---: |\n"
    for r in results:
        status_icon = "SUCCESS" if r["status"] == "success" else "FAILED"
        md_content += f"| `{r['file_name']}` | {r['total_triples']:,} | {r['validated_subjects']:,} | {r['errors_count'] + r['critical_errors_count']} | {r['warnings_count']} | {status_icon} |\n"
    md_content += "\n## 3. Detailed Findings\n\n"
    findings_count = 0
    for r in results:
        md_content += f"### 3.{findings_count + 1} File: `{r['file_name']}`\n"
        if not r["findings"]:
            md_content += (
                "No semantic anomalies or violations detected in this file.\n\n"
            )
        else:
            md_content += (
                "| RDF Subject | Property / Predicate | Level | Description | Rule |\n"
            )
            md_content += "| :--- | :--- | :---: | :--- | :--- |\n"
            displayed_findings = r["findings"][:100]
            for f in displayed_findings:
                subj_short = (
                    f["subject"].split("/")[-1] if "/" in f["subject"] else f["subject"]
                )
                prop_short = (
                    f["property"].split("#")[-1]
                    if "#" in f["property"]
                    else f["property"].split("/")[-1]
                    if "/" in f["property"]
                    else f["property"]
                )
                md_content += f"| `...{subj_short}` | `{prop_short}` | **{f['level']}** | {f['message']} | {f['rule']} |\n"
            if len(r["findings"]) > 100:
                md_content += f"\n*... and {len(r['findings']) - 100} additional findings recorded in JSON report file.*\n"
            md_content += "\n"
        findings_count += 1
    md_content += "\n## 4. Architectural Recommendations\n\n1. Missing Mandatory Properties:\n   Add fallback handling in parser to populate default values where upstream feeds omit expected fields.\n\n2. Target References:\n   Ensure related modular graphs are loaded together in the triplestore to resolve cross-graph pointers.\n\n3. Sanitization Consistency:\n   Verify identifier sanitization preserves clean standard formats.\n"
    with open(md_report_file, "w", encoding="utf-8") as f:
        f.write(md_content)
    print(f"[Validation] Markdown report written to: {md_report_file}")
    json_data = {
        "timestamp": timestamp_readable,
        "compliance_score": quality_score,
        "quality_tier": quality_tier,
        "statistics": {
            "total_files": total_files,
            "successful_parses": successful_parses,
            "failed_parses": failed_parses,
            "total_triples": total_triples,
            "total_subjects": total_subjects,
            "critical_errors": total_critical,
            "errors": total_errors,
            "warnings": total_warnings,
        },
        "results": results,
    }
    with open(json_report_file, "w", encoding="utf-8") as f:
        json.dump(json_data, f, indent=2)
    print(f"[Validation] JSON report written to: {json_report_file}")
    summary_message = f"Semantic quality assurance complete for {total_files} Turtle files. Compliance Score: {quality_score_str} ({quality_tier}). Found {total_errors} Errors and {total_warnings} Warnings. Reports saved to {md_report_file} and {json_report_file}."
    print(f"[Validation] Summary: {summary_message}")
    return {"all_done": True, "summary": summary_message}
